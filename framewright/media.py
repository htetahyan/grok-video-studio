from .util import (MODELS, FwError, Production, ffmpeg, ffprobe_json, filter_path,
                   fontfile, have, rel, save_json, say, sha256)

DEMO_LINE = ("This is a synthetic test clip for the Framewright toolkit. "
             "Every cut gets measured sound, clear captions, and stills as proof.")


# ------------------------------------------------------------------ test clip
def _piper_cmd() -> list[str] | None:
    exe = Path(sys.executable).parent / "piper"
    if exe.exists():
        return [str(exe)]
    if have("piper"):
        return ["piper"]
    return None


def _voice_line(text: str, out_wav: Path) -> bool:
    model = Path(os.environ.get("FW_PIPER_VOICE", MODELS / "piper" / "en_US-lessac-medium.onnx"))
    cmd = _piper_cmd()
    if not cmd or not model.exists():
        say("piper or voice model not found — test clip will use tone only")
        return False
    res = subprocess.run([*cmd, "-m", str(model), "-f", str(out_wav)], input=text,
                         text=True, capture_output=True)
    if res.returncode != 0 or not out_wav.exists():
        say("piper failed — tone only: " + (res.stderr or "")[-300:])
        return False
    return True


def testclip(out: Path, seconds: float = 0, text: str = DEMO_LINE) -> dict:
    """Generate a clearly-labelled synthetic clip (1920x1080 30p, stereo 48k)."""
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as td:
        voice = Path(td) / "voice.wav"
        has_voice = _voice_line(text, voice)
        vdur = probe_duration(voice) if has_voice else 0
        dur = max(seconds or 0, vdur + 2.0, 8.0)
        font = fontfile()
        ff = f"fontfile={filter_path(Path(font))}:" if font else ""
        label = (f"drawtext={ff}text='SYNTHETIC TEST MATERIAL':fontsize=54:fontcolor=white:"
                 f"box=1:boxcolor=black@0.6:boxborderw=18:x=(w-tw)/2:y=60,"
                 f"drawtext={ff}text='framewright testclip  %{{pts\\:hms}}':fontsize=30:"
                 f"fontcolor=yellow:box=1:boxcolor=black@0.5:boxborderw=10:x=40:y=h-80")
        args = ["-f", "lavfi", "-i", f"testsrc2=size=1920x1080:rate=30:duration={dur:.2f}",
                "-f", "lavfi", "-i", f"sine=frequency=220:sample_rate=48000:duration={dur:.2f}"]
        if has_voice:
            args += ["-i", str(voice)]
            afilter = ("[1:a]volume=0.03[bed];[2:a]aresample=48000,adelay=1000:all=1,volume=0.45[vo];"
                       "[bed][vo]amix=inputs=2:duration=first:normalize=0,pan=stereo|c0=c0|c1=c0[a]")
        else:
            afilter = "[1:a]volume=0.1,pan=stereo|c0=c0|c1=c0[a]"
        ffmpeg([*args, "-filter_complex", f"[0:v]{label}[v];{afilter}", "-map", "[v]", "-map", "[a]",
                "-c:v", "libx264", "-crf", "20", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "192k",
                "-ar", "48000", "-t", f"{dur:.2f}", "-movflags", "+faststart",
                "-metadata", "comment=SYNTHETIC TEST MATERIAL generated by framewright", str(out)])
    say(f"test clip: {out} ({dur:.1f}s, voice={'piper' if has_voice else 'none'})")
    return {"file": str(out), "duration": dur, "voice": has_voice, "script": text if has_voice else ""}


def probe_duration(path: Path) -> float:
    return float(ffprobe_json(path)["format"].get("duration", 0) or 0)


# --------------------------------------------------------------------- intake
def intake(prod: Production, files: list[Path], source: str, license: str,
           note: str = "", synthetic: bool = False) -> list[Path]:
    """Copy media into intake/, seal it read-only, probe it, log provenance."""
    prod.check_claim()
    landed = []
    prod.intake.mkdir(parents=True, exist_ok=True)
    prod.intake.chmod(0o755)  # unseal the folder only while adding
    try:
        _intake_files(prod, files, source, license, note, synthetic, landed)
    finally:
        prod.intake.chmod(0o555)  # folder sealed again: no new/renamed/deleted files by accident
    return landed


def _intake_files(prod, files, source, license, note, synthetic, landed) -> None:
    for f in files:
        f = Path(f)
        if not f.is_file():
            raise FwError(f"not a file: {f}")
        digest = sha256(f)
        dest = prod.intake / f.name
        if dest.exists():
            if sha256(dest) == digest:
                say(f"{f.name}: already in intake (same hash) — skipped")
                landed.append(dest)
                continue
            stem, n = dest.stem, 2
            while dest.exists():
                dest = prod.intake / f"{stem}__{n}{f.suffix}"
                n += 1
        shutil.copy2(f, dest)
        dest.chmod(0o444)
        card = spec_card(dest, prod.proof / "spec")
        prod.log("intake", file=rel(dest, prod.root), sha256=digest, origin=str(f),
                 source=source, license=license, synthetic=synthetic, note=note,
                 spec=rel(card, prod.root))
        say(f"sealed {dest.name} (sha256 {digest[:12]}…)")
        landed.append(dest)


# ------------------------------------------------------------------ spec card
def _fps(s: str) -> float:
    try:
        return float(Fraction(s))
    except Exception:
        return 0.0


def summarize(info: dict) -> dict:
    fmt = info.get("format", {})
    out = {"container": fmt.get("format_name"), "duration": round(float(fmt.get("duration", 0) or 0), 3),
           "size_bytes": int(fmt.get("size", 0) or 0), "bitrate": int(fmt.get("bit_rate", 0) or 0),
           "video": None, "audio": None, "subtitle_streams": 0}
    for st in info.get("streams", []):
        t = st.get("codec_type")
        if t == "video" and out["video"] is None and st.get("disposition", {}).get("attached_pic", 0) == 0:
            out["video"] = {"codec": st.get("codec_name"), "profile": st.get("profile"),
                            "width": st.get("width"), "height": st.get("height"),
                            "fps": round(_fps(st.get("avg_frame_rate", "0/1")), 3),
                            "pix_fmt": st.get("pix_fmt"), "color_space": st.get("color_space"),
                            "color_transfer": st.get("color_transfer"),
                            "sar": st.get("sample_aspect_ratio"), "frames": st.get("nb_frames")}
        elif t == "audio" and out["audio"] is None:
            out["audio"] = {"codec": st.get("codec_name"), "sample_rate": int(st.get("sample_rate", 0) or 0),
                            "channels": st.get("channels"), "layout": st.get("channel_layout"),
                            "bitrate": int(st.get("bit_rate", 0) or 0)}
        elif t == "subtitle":
            out["subtitle_streams"] += 1
    return out


def spec_md(name: str, s: dict) -> str:
    v, a = s.get("video") or {}, s.get("audio") or {}
    rows = [("container", s["container"]), ("duration", f"{s['duration']:.3f} s"),
            ("size", f"{s['size_bytes']/1e6:.2f} MB"), ("bitrate", f"{s['bitrate']/1000:.0f} kb/s")]
    if v:
        rows += [("video", f"{v['codec']} {v.get('profile') or ''}".strip()),
                 ("frame", f"{v['width']}x{v['height']} @ {v['fps']} fps, {v['pix_fmt']}"),
                 ("color", f"{v.get('color_space') or 'unset'} / {v.get('color_transfer') or 'unset'}")]
    if a:
        rows += [("audio", f"{a['codec']} {a['sample_rate']} Hz, {a['channels']} ch ({a.get('layout')})")]
    body = "\n".join(f"| {k} | {val} |" for k, val in rows)
    return f"### Spec card — {name}\n\n| field | value |\n|---|---|\n{body}\n"


def spec_card(path: Path, outdir: Path) -> Path:
    """ffprobe -> <outdir>/<name>.json (raw + summary) and .md (human card)."""
    outdir.mkdir(parents=True, exist_ok=True)
    info = ffprobe_json(path)
    s = summarize(info)
    jp = outdir / f"{path.name}.json"
    save_json(jp, {"file": str(path), "summary": s, "ffprobe": info})
    (outdir / f"{path.name}.md").write_text(spec_md(path.name, s))
    return jp


# --------------------------------------------------------------------- stills
def stills(video: Path, outdir: Path, count: int = 6, at: list[float] | None = None,
           cols: int = 4, sheet_frames: int = 12) -> dict:
    """Export full-res PNG stills at chosen/evenly spaced times + a timestamped contact sheet."""
    outdir.mkdir(parents=True, exist_ok=True)
    dur = probe_duration(video)
    if not at:
        at = [round(dur * (i + 0.5) / count, 3) for i in range(count)]
    files = []
    for t in at:
        f = outdir / f"{video.stem}_t{t:08.3f}.png"
        ffmpeg(["-ss", f"{t:.3f}", "-i", str(video), "-frames:v", "1", "-update", "1", str(f)], quiet=True)
        files.append(f)
    rows = -(-sheet_frames // cols)
    font = fontfile()
    ff = f"fontfile={filter_path(Path(font))}:" if font else ""
    sheet = outdir / f"{video.stem}_sheet.jpg"
    rate = sheet_frames / max(dur, 0.1)
    vf = (f"fps={rate:.6f},scale=480:-2,"
          f"drawtext={ff}text='%{{pts\\:hms}}':fontsize=18:fontcolor=white:box=1:boxcolor=black@0.6:x=w-tw-8:y=h-th-8,"
          f"tile={cols}x{rows}:padding=6:margin=6:color=0x202020")
    ffmpeg(["-i", str(video), "-vf", vf, "-frames:v", "1", "-q:v", "3", "-update", "1", str(sheet)], quiet=True)
    say(f"{len(files)} stills + contact sheet in {outdir}")
    return {"stills": [str(f) for f in files], "sheet": str(sheet), "times": at}
